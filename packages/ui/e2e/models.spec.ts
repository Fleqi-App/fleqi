import { expect, test } from "@playwright/test";

test("模型/API：手动配置、获取保留、用途保存、嵌套弹层焦点及最小尺寸", async ({ page }) => {
  await page.goto("/#/console/about?settings=models");
  await page.getByRole("button", { name: "连接 OpenAI", exact: true }).click();
  const editor = page.getByRole("dialog", { name: "模型连接", exact: true });
  await editor.getByLabel("手动模型 ID").fill("manual-model");
  await editor.getByRole("button", { name: "添加模型", exact: true }).click();
  await editor.getByLabel("默认生成模型", { exact: true }).selectOption("manual-model");
  await editor.getByLabel("摘要模型（可选）").selectOption("manual-model");
  await editor.getByRole("button", { name: "获取模型", exact: true }).click();
  await expect(editor.getByText(/获取成功/)).toBeVisible();
  await expect(editor.getByLabel("默认生成模型", { exact: true })).toHaveValue("manual-model");
  await editor.getByLabel("搜索模型").fill("manual");
  await expect(editor.getByTestId("model-row-manual-model")).toBeVisible();
  await expect(editor.getByTestId("model-row-preview-mini")).toHaveCount(0);
  await editor.getByRole("button", { name: "测试模型", exact: true }).click();
  await expect(editor.getByText(/调用成功/)).toBeVisible();
  await editor.getByLabel("搜索模型").clear();
  await page.screenshot({ path: "../../tests/.artifacts/models-editor-browser.png" });
  await editor.getByRole("button", { name: "保存端点", exact: true }).click();
  await expect(editor).not.toBeVisible();
  const settings = page.getByRole("dialog", { name: "设置", exact: true });
  const defaultSelect = settings.getByLabel("默认模型", { exact: true });
  const model = await defaultSelect.locator("option").filter({ hasText: "OpenAI / manual-model" }).getAttribute("value");
  await defaultSelect.selectOption(model!);
  await expect(settings.getByText("已保存", { exact: true })).toBeVisible();
  await settings.getByLabel("结果摘要模型").selectOption(model!);
  await expect(settings.locator("[data-settings-revision='2']")).toBeVisible();
  await settings.getByRole("button", { name: "编辑端点 OpenAI" }).click();
  await editor.getByLabel("显示名称").fill("OpenAI 工作连接");
  await page.evaluate(() => { window.location.hash = "#/console/about?settings=appearance"; });
  const discard = page.getByRole("dialog", { name: "放弃修改？" });
  await expect(discard).toBeVisible();
  await expect(page).toHaveURL(/settings=models$/);
  await discard.getByRole("button", { name: "继续编辑" }).click();
  await expect(editor.getByLabel("显示名称")).toBeFocused();
  await expect(editor.getByLabel("显示名称")).toHaveValue("OpenAI 工作连接");
  await page.keyboard.press("Escape");
  await expect(discard).toBeVisible();
  await discard.getByRole("button", { name: "继续编辑" }).click();
  await expect(editor.getByLabel("显示名称")).toHaveValue("OpenAI 工作连接");
  await page.setViewportSize({ width: 640, height: 520 });
  const bounds = (await editor.boundingBox())!;
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.y).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(640);
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(520);
  expect(await editor.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await editor.getByRole("button", { name: "取消编辑" }).click();
  await discard.getByRole("button", { name: "放弃修改" }).click();
  expect(await settings.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await settings.getByRole("button", { name: "删除端点 OpenAI" }).click();
  await page.getByRole("dialog", { name: "删除连接" }).getByRole("button", { name: "确认删除" }).click();
  await expect(settings.getByText("选定模型已被删除或不再可用，请重新选择。")).toBeVisible();
});
